def ensure_no_symlink(path: Path, label: str) -> None:
    if path.is_symlink():
        fail(f"{label} must not be a symlink: {path}")


def source_files(source: Path) -> list[Path]:
    files: list[Path] = []
    for path in sorted(source.rglob("*")):
        if path.is_symlink():
            fail(f"plugin source contains a symlink: {path}")
        relative = path.relative_to(source)
        # Generated trees are never source provenance. Check symlinks before
        # pruning so a top-level generated symlink cannot bypass the source
        # safety gate. Legacy generated entries remain untouched in targets.
        if _is_generated(relative):
            continue
        if path.is_file():
            files.append(relative)
    if not files:
        fail(f"plugin source is empty: {source}")
    return files


def target_files(target: Path) -> tuple[set[Path], set[Path]]:
    """Return regular files and symlink paths below target."""

    files: set[Path] = set()
    symlinks: set[Path] = set()
    for path in sorted(target.rglob("*")):
        relative = path.relative_to(target)
        if path.is_symlink():
            symlinks.add(relative)
        elif path.is_file():
            files.add(relative)
    return files, symlinks


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    ensure_no_symlink(path, "managed file")
    try:
        return sha256_bytes(path.read_bytes())
    except OSError as exc:
        fail(f"cannot hash {path}: {exc}")


def persistence_catalog_hashes(harness: Path) -> dict[str, str]:
    """Hash generated persistence artifacts without following symlinks."""

    result: dict[str, str] = {}
    for relative in PERSISTENCE_CATALOG_RELATIVES:
        path = harness / relative
        ensure_no_symlink(path, "persistence catalog artifact")
        if not path.is_file():
            fail(f"persistence catalog artifact is missing: {path}")
        result[relative.as_posix()] = sha256_file(path)
    return result


def tree_digest(file_hashes: dict[str, str]) -> str:
    """Hash sorted relative names and file hashes for a deterministic tree id."""

    digest = hashlib.sha256()
    for relative in sorted(file_hashes):
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        digest.update(file_hashes[relative].encode("ascii"))
        digest.update(b"\n")
    return digest.hexdigest()


def validate_source(source: Path, expected_package: str, label: str) -> list[Path]:
    package_file = source / "package.json"
    if not package_file.is_file():
        fail(f"{label} source has no package.json: {package_file}")
    try:
        package = json.loads(package_file.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        fail(f"cannot parse {label} package.json: {exc}")
    if package.get("name") != expected_package:
        fail(
            f"{label} source package name drifted: "
            f"expected {expected_package!r}, got {package.get('name')!r}"
        )
    return source_files(source)


def validate_hash_map(value: object, label: str) -> dict[str, str]:
    if not isinstance(value, dict):
        fail(f"managed manifest {label} must be an object")
    result: dict[str, str] = {}
    for key, item in value.items():
        key_path = Path(key) if isinstance(key, str) else Path(".")
        if (
            not isinstance(key, str)
            or not key
            or key_path.is_absolute()
            or any(part in {"", ".", ".."} for part in key_path.parts)
            or "\\" in key
        ):
            fail(f"managed manifest {label} contains an invalid path")
        if not isinstance(item, str) or not HEX64_RE.fullmatch(item):
            fail(f"managed manifest {label} contains an invalid SHA-256: {key}")
        result[key] = item
    return result


def load_manifest(target: Path) -> dict[str, object] | None:
    """Load and structurally validate the managed manifest, if present."""

    managed_dir = target / MANAGED_DIR
    manifest_path = target / MANIFEST_RELATIVE
    if managed_dir.is_symlink():
        fail(f"managed directory must not be a symlink: {managed_dir}")
    if manifest_path.is_symlink():
        fail(f"managed manifest must not be a symlink: {manifest_path}")
    if not manifest_path.exists():
        if managed_dir.exists() and not managed_dir.is_dir():
            fail(f"managed path is not a directory: {managed_dir}")
        return None
    if not managed_dir.is_dir():
        fail(f"managed manifest parent is not a directory: {managed_dir}")
    try:
        data = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        fail(f"cannot parse managed manifest {manifest_path}: {exc}")
    if not isinstance(data, dict):
        fail(f"managed manifest must be an object: {manifest_path}")
    if data.get("schemaVersion") != MANIFEST_SCHEMA:
        fail(f"unsupported managed manifest schemaVersion: {manifest_path}")
    if data.get("installer") != "dsh-plugin":
        fail(f"managed manifest installer identity drifted: {manifest_path}")
    if data.get("target") != PLUGIN_TARGET.as_posix():
        fail(f"managed manifest target drifted: {manifest_path}")
    if data.get("source") != "dsh-plugin":
        fail(f"managed manifest source drifted: {manifest_path}")

    files = validate_hash_map(data.get("files"), "files")
    source_digest = data.get("sourceTreeSha256")
    if not isinstance(source_digest, str) or not HEX64_RE.fullmatch(source_digest):
        fail(f"managed manifest sourceTreeSha256 is invalid: {manifest_path}")
    if tree_digest(files) != source_digest:
        fail(f"managed manifest sourceTreeSha256 does not match files: {manifest_path}")

    host_files_value = data.get("hostFiles")
    host_source_digest = data.get("hostSourceTreeSha256")
    if host_files_value is not None or host_source_digest is not None:
        host_files = validate_hash_map(host_files_value, "hostFiles")
        if not isinstance(host_source_digest, str) or not HEX64_RE.fullmatch(
            host_source_digest
        ):
            fail(f"managed manifest hostSourceTreeSha256 is invalid: {manifest_path}")
        if tree_digest(host_files) != host_source_digest:
            fail(
                "managed manifest hostSourceTreeSha256 does not match hostFiles: "
                f"{manifest_path}"
            )

    registrations = validate_hash_map(data.get("registrations"), "registrations")
    expected_registration_sets = {
        frozenset(path.as_posix() for path in REGISTRATION_RELATIVES),
        frozenset(path.as_posix() for path in LEGACY_CODEX_REGISTRATION_RELATIVES),
        frozenset(path.as_posix() for path in LEGACY_HOST_CODEX_REGISTRATION_RELATIVES),
        frozenset(path.as_posix() for path in LEGACY_SPLIT_REGISTRATION_RELATIVES),
        frozenset(path.as_posix() for path in LEGACY_REGISTRATION_RELATIVES),
    }
    if frozenset(registrations) not in expected_registration_sets:
        fail(f"managed manifest registrations are incomplete: {manifest_path}")

    catalog = data.get("catalog")
    if catalog is not None:
        if not isinstance(catalog, dict):
            fail(f"managed manifest catalog must be an object or omitted: {manifest_path}")
        if catalog.get("generator") != "gen-persistence-catalog":
            fail(f"managed manifest catalog generator drifted: {manifest_path}")
        catalog_files = validate_hash_map(catalog.get("files"), "catalog.files")
        expected_catalog = {path.as_posix() for path in PERSISTENCE_CATALOG_RELATIVES}
        if set(catalog_files) != expected_catalog:
            fail(f"managed manifest catalog files are incomplete: {manifest_path}")

    lock = data.get("lock")
    if lock is not None:
        if not isinstance(lock, dict):
            fail(f"managed manifest lock must be an object or null: {manifest_path}")
        if lock.get("path") != "pnpm-lock.yaml":
            fail(f"managed manifest lock path drifted: {manifest_path}")
        if not isinstance(lock.get("sha256"), str) or not HEX64_RE.fullmatch(lock["sha256"]):
            fail(f"managed manifest lock SHA-256 is invalid: {manifest_path}")
        version = lock.get("pnpmVersion")
        if version is not None and (not isinstance(version, str) or not version):
            fail(f"managed manifest pnpmVersion is invalid: {manifest_path}")
    return data


def validate_manifest_registrations(
    harness: Path, manifest: dict[str, object] | None
) -> None:
    if manifest is None:
        return
    registrations = manifest["registrations"]
    assert isinstance(registrations, dict)
    for relative, expected in registrations.items():
        path = harness / relative
        actual = sha256_file(path)
        if actual != expected:
            fail(
                "managed DSH registration anchor drifted; refusing to overwrite: "
                f"{relative}"
            )


def _is_generated(relative: Path) -> bool:
    return bool(relative.parts) and relative.parts[0] in GENERATED_TOP_LEVEL


def assembled_client_tsconfig(source: Path) -> bytes:
    """Rewrite the standalone client leaf for its installed workspace path.

    The source checkout intentionally extends the pinned harness through
    ``../.runtime/deepseek-harness`` so it can typecheck in this repository.
    Once copied below ``packages/client/ui-voice`` the same references must be
    rooted at the harness checkout itself.  This is a target-only transform;
    the source file is never modified and the transformed bytes are recorded
    in the managed manifest so reruns remain drift-checked.
    """

    try:
        text = source.read_text(encoding="utf-8")
    except OSError as exc:
        fail(f"cannot read standalone client tsconfig {source}: {exc}")
    standalone_prefix = "../.runtime/deepseek-harness/"
    workspace_prefix = "../../../"
    if standalone_prefix not in text:
        fail(
            "standalone client tsconfig must contain the exact pinned harness "
            f"prefix {standalone_prefix!r}: {source}"
        )
    result = text.replace(standalone_prefix, workspace_prefix)
    if standalone_prefix in result or "../.runtime/deepseek-harness" in result:
        fail(f"assembled client tsconfig retained a standalone .runtime path: {source}")
    if '"extends": "../../../tsconfig.base.client.json"' not in result:
        fail(f"assembled client tsconfig has no workspace-relative base config: {source}")
    return result.encode("utf-8")


def assembled_host_tsconfig(source: Path) -> bytes:
    """Rewrite the standalone Codex Host leaf for its installed workspace path.

    The Host source lives beside ``.runtime/deepseek-harness`` in this
    repository, while the installed package lives at
    ``packages/host/codex``.  Package references therefore need one extra
    mapping: a source ``.../packages/core/...`` reference becomes
    ``../../core/...`` from the installed Host package; vendor references
    remain rooted at ``../../../vendor``.
    """

    try:
        text = source.read_text(encoding="utf-8")
    except OSError as exc:
        fail(f"cannot read standalone Host tsconfig {source}: {exc}")
    standalone_prefix = "../.runtime/deepseek-harness/"
    if standalone_prefix not in text:
        fail(
            "standalone Host tsconfig must contain the exact pinned harness "
            f"prefix {standalone_prefix!r}: {source}"
        )
    result = text.replace(
        standalone_prefix + "packages/", "../../"
    ).replace(
        standalone_prefix + "vendor/", "../../../vendor/"
    ).replace(standalone_prefix, "../../../")
    if standalone_prefix in result or "../.runtime/deepseek-harness" in result:
        fail(f"assembled Host tsconfig retained a standalone .runtime path: {source}")
    if '"extends": "../../../tsconfig.base.json"' not in result:
        fail(f"assembled Host tsconfig has no workspace-relative base config: {source}")
    return result.encode("utf-8")


def assembled_host_test_source(source: Path, relative: Path) -> bytes | None:
    """Rewrite standalone Host integration-test runtime imports only."""

    if not relative.as_posix().startswith("tests/") or not relative.name.endswith(".host.spec.ts"):
        return None
    try:
        text = (source / relative).read_text(encoding="utf-8")
    except OSError as exc:
        fail(f"cannot read standalone Host test {source / relative}: {exc}")
    standalone_prefix = "../../.runtime/deepseek-harness/"
    if standalone_prefix not in text:
        return None
    # Installed tests are four directories below the harness root:
    # packages/host/codex/tests -> ../../../../.
    return text.replace(standalone_prefix, "../../../../").encode("utf-8")


def validate_target_generated_files(
    target_file_set: set[Path], symlink_set: set[Path]
) -> None:
    # Generated output is ignored only below an exact top-level directory.
    # The directory itself must not be a symlink: accepting ``lib -> …`` (or
    # ``node_modules -> …``) would make later mkdir/copy operations follow a
    # path outside the managed target.  Package-manager links *inside*
    # node_modules are an expected generated shape, however, and are never
    # traversed or copied by this installer; links in lib/.turbo/.cache are
    # not expected and remain rejected.
    unsafe_symlinks = sorted(
        relative
        for relative in symlink_set
        if (
            not _is_generated(relative)
            or len(relative.parts) == 1
            or relative.parts[0] != "node_modules"
        )
    )
    if unsafe_symlinks:
        fail(
            "plugin target contains symlink(s); refusing to follow or replace: "
            + ", ".join(str(path) for path in unsafe_symlinks)
        )

    for relative in target_file_set:
        if relative.parts and relative.parts[0] == MANAGED_DIR.name:
            if relative != MANIFEST_RELATIVE:
                fail(
                    "managed directory contains an unexpected file; refusing to "
                    f"modify it: {relative}"
                )


def validate_plugin_tree(
    source: Path,
    target: Path,
    files: Iterable[Path],
    manifest: dict[str, object] | None,
    *,
    manifest_key: str = "files",
    label: str = "plugin",
    transformed_files: dict[Path, bytes] | None = None,
) -> tuple[list[Path], list[Path], dict[str, str]]:
    """Preflight one managed source tree without changing the target."""

    expected = set(files)
    transformed_files = transformed_files or {}
    source_hashes = {
        relative.as_posix(): sha256_bytes(transformed_files[relative])
        if relative in transformed_files
        else sha256_file(source / relative)
        for relative in expected
    }
    old_hashes = (
        validate_hash_map(manifest.get(manifest_key), manifest_key)
        if manifest and manifest.get(manifest_key) is not None
        else {}
    )

    if target.exists():
        ensure_no_symlink(target, f"{label} target")
        if not target.is_dir():
            fail(f"{label} target is not a directory: {target}")
        target_file_set, symlink_set = target_files(target)
        validate_target_generated_files(target_file_set, symlink_set)
    else:
        target_file_set = set()

    # Generated output may be present in a legacy manifest or in the target,
    # but it is never provenance for the source overlay.  Keep the complete
    # source hash map for the eventual manifest/copy plan while excluding
    # exact generated top-level paths from adoption/drift comparisons.
    expected_strings = {
        relative
        for relative in source_hashes
        if not _is_generated(Path(relative))
    }
    current_hashes: dict[str, str] = {}
    for relative in sorted(expected & target_file_set):
        if _is_generated(relative):
            continue
        current_hashes[relative.as_posix()] = sha256_file(target / relative)

    if manifest is not None:
        missing_old = sorted(set(current_hashes) - set(old_hashes))
        if missing_old:
            fail(
                f"{label} target contains files outside its managed manifest; "
                "refusing to overwrite: "
                + ", ".join(missing_old)
            )
        changed_old = sorted(
            relative
            for relative, actual in current_hashes.items()
            if old_hashes.get(relative) != actual
        )
        if changed_old:
            fail(
                f"{label} target drifted; refusing to overwrite: "
                + ", ".join(changed_old)
            )
    else:
        # A pre-manifest target has no provenance that can justify replacing
        # an existing file.  An empty target is installable; a non-empty target
        # may only be adopted when its complete source tree already matches
        # this source byte-for-byte.  Generated directories are intentionally
        # excluded from this comparison by _is_generated below.
        non_generated_files = {
            relative.as_posix()
            for relative in target_file_set
            if not _is_generated(relative) and relative != MANIFEST_RELATIVE
        }
        if non_generated_files:
            if non_generated_files != expected_strings:
                missing = sorted(expected_strings - non_generated_files)
                extras = sorted(non_generated_files - expected_strings)
                details = []
                if missing:
                    details.append("missing: " + ", ".join(missing))
                if extras:
                    details.append("extra: " + ", ".join(extras))
                fail(
                    f"manifestless {label} target is not a complete current source "
                    "tree; refusing to adopt: " + "; ".join(details)
                )
            changed = sorted(
                relative
                for relative, actual in current_hashes.items()
                if actual != source_hashes[relative]
            )
            if changed:
                fail(
                    f"manifestless {label} target differs from current source; "
                    "refusing to overwrite: " + ", ".join(changed)
                )

    obsolete: set[Path] = set()
    if manifest is not None:
        for relative in sorted(set(old_hashes) - expected_strings):
            if _is_generated(Path(relative)):
                # Build outputs are never removed by overlay reconciliation,
                # even when an older manifest recorded them as managed.
                continue
            path = target / relative
            if not path.exists():
                continue
            if path.is_symlink():
                fail(f"managed obsolete {label} file is a symlink; refusing to remove: {relative}")
            actual = sha256_file(path)
            if actual != old_hashes[relative]:
                fail(f"managed obsolete file drifted; refusing to remove: {relative}")
            obsolete.add(Path(relative))

    extras = sorted(
        relative
        for relative in target_file_set - expected
        if not _is_generated(relative)
        and relative != MANIFEST_RELATIVE
        and relative not in obsolete
    )
    if extras:
        fail(
            f"{label} target contains unexpected files; refusing to delete them: "
            + ", ".join(str(path) for path in extras)
        )

    missing_or_changed: list[Path] = []
    for relative in sorted(expected):
        destination = target / relative
        if relative not in target_file_set:
            missing_or_changed.append(relative)
        elif sha256_file(destination) != source_hashes[relative.as_posix()]:
            missing_or_changed.append(relative)
    return missing_or_changed, sorted(obsolete), source_hashes


def split_lines(text: str) -> tuple[list[str], str]:
    newline = "\r\n" if "\r\n" in text else "\n"
    return text.splitlines(keepends=True), newline


def line_without_ending(line: str) -> str:
    return line.removesuffix("\n").removesuffix("\r")


def rewrite_tsconfig(path: Path, dry_run: bool) -> tuple[str, bool]:
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        fail(f"cannot read {path}: {exc}")
    lines, newline = split_lines(text)

    voice_token = "packages/client/ui-voice"
    entry_re = re.compile(
        r'^(?P<indent>[ \t]*)\{[ \t]*"path"[ \t]*:[ \t]*'
        r'"\./packages/client/ui-voice(?:/tsconfig\.client\.json)?"'
        r'[ \t]*\}[,]?[ \t]*(?://.*)?$'
    )
    voice_lines = [index for index, line in enumerate(lines) if voice_token in line]
    valid_entries = [
        index for index, line in enumerate(lines)
        if entry_re.fullmatch(line_without_ending(line))
    ]
    if voice_lines and (len(voice_lines) != 1 or len(valid_entries) != 1):
        fail(f"tsconfig.client.json has a malformed or duplicate ui-voice entry: {path}")

    anchor_re = re.compile(
        r'^(?P<indent>[ \t]*)\{[ \t]*"path"[ \t]*:[ \t]*'
        r'"\./packages/client/ui-trajectory"[ \t]*\},[ \t]*(?://.*)?$'
    )
    anchors = [
        index
        for index, line in enumerate(lines)
        if anchor_re.fullmatch(line_without_ending(line))
    ]
    if len(anchors) != 1:
        fail(
            "tsconfig.client.json must contain exactly one comma-terminated "
            f"ui-trajectory anchor; found {len(anchors)}: {path}"
        )

    if valid_entries:
        index = valid_entries[0]
        line = line_without_ending(lines[index])
        if '"./packages/client/ui-voice"' in line:
            return text, False
        match = entry_re.fullmatch(line)
        assert match is not None
        replacement = (
            match.group("indent")
            + '{ "path": "./packages/client/ui-voice" },'
            + newline
        )
        new_lines = list(lines)
