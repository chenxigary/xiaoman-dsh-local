#!/usr/bin/env python3
"""Install the repository's DSH Client and Codex Host overlays into one harness.

The installer is intentionally conservative.  It validates both complete
source trees and every DSH registration anchor before writing anything.
After the first successful install, ``.dsh-managed/manifest.json`` records a
hash for every managed file and for each registration file.  A later source
revision may replace files only when the target still matches that manifest;
an edit made in the harness therefore fails closed instead of being silently
overwritten.  The manifest itself lives below a generated directory and is
not part of either source tree.

There is no recursive delete operation.  Obsolete files from a previous
managed manifest are removed one at a time only after their recorded hash is
verified.  Build output and package-manager directories remain untouched.
"""

